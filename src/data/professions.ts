// Utility per ottenere lista flat di professioni (compatibilità backward)
export const getProfessionsList = (): string[] => {
  return professions.flatMap(p => 
    p.maschile === p.femminile 
      ? [p.maschile] 
      : [p.maschile, p.femminile]
  );
};

// Utility per ottenere display string (es. "Cuoco / Cuoca")
export const getProfessionDisplay = (profession: Profession): string => {
  if (profession.maschile === profession.femminile) {
    return profession.maschile;
  }
  return `${profession.maschile} / ${profession.femminile}`;
};
